-- An uploaded fixture is immutable evidence for one exact procedure revision.
CREATE TABLE IF NOT EXISTS validation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_history_id BIGINT NOT NULL REFERENCES procedure_history(id),
    source_filename VARCHAR(255) NOT NULL,
    source_sha256 CHAR(64) NOT NULL,
    source_format VARCHAR(16) NOT NULL,
    recorded_by VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(32) NOT NULL DEFAULT 'RECEIVED',
    total_readings INTEGER NOT NULL DEFAULT 0,
    matched_count INTEGER NOT NULL DEFAULT 0,
    mismatched_count INTEGER NOT NULL DEFAULT 0,
    outlier_count INTEGER NOT NULL DEFAULT 0,
    missing_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_validation_run_source UNIQUE (procedure_history_id, source_sha256),
    CONSTRAINT chk_validation_run_format CHECK (source_format IN ('CSV', 'JSON')),
    CONSTRAINT chk_validation_run_status CHECK (status IN ('RECEIVED', 'VALIDATED', 'REJECTED')),
    CONSTRAINT chk_validation_run_counts CHECK (
        total_readings >= 0 AND matched_count >= 0 AND mismatched_count >= 0
        AND outlier_count >= 0 AND missing_count >= 0
    )
);

CREATE INDEX IF NOT EXISTS idx_validation_run_history ON validation_runs (procedure_history_id);
CREATE INDEX IF NOT EXISTS idx_validation_run_uploaded_at ON validation_runs (uploaded_at);
