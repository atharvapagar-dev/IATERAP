CREATE TABLE IF NOT EXISTS test_procedures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lru_id BIGINT NOT NULL REFERENCES lru(id),
    name VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    approval_status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    version_number INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_test_procedure_entity_approval_status
        CHECK (approval_status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED'))
);

CREATE INDEX IF NOT EXISTS idx_test_procedure_lru ON test_procedures (lru_id);

ALTER TABLE test_steps ADD COLUMN IF NOT EXISTS test_procedure_id BIGINT REFERENCES test_procedures(id);
CREATE INDEX IF NOT EXISTS idx_test_step_procedure ON test_steps (test_procedure_id);