-- V16: Reviewer Comments (AI-174 / T6-B2).
--
-- A comment is anchored to a specific, immutable procedure_history
-- revision, and optionally to a specific TestStep. author is a plain
-- username string, following the same convention already established by
-- audit_log.actor and procedure_history.created_by, rather than a new
-- User FK (PART U: "do not duplicate User" -- the identity model stays
-- consistent with the rest of the schema, no parallel relation added).

CREATE TABLE IF NOT EXISTS reviewer_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_history_id BIGINT NOT NULL REFERENCES procedure_history(id),
    test_step_id BIGINT REFERENCES test_steps(id),
    author VARCHAR(255) NOT NULL,
    comment_text VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_reviewer_comment_revision ON reviewer_comments (procedure_history_id);
CREATE INDEX IF NOT EXISTS idx_reviewer_comment_test_step ON reviewer_comments (test_step_id);
