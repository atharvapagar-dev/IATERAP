-- Immutable execution evidence for the fault-injection engine.
-- A run is always tied to the exact procedure snapshot selected after approval;
-- it must never be re-pointed at a later revision of the procedure.
CREATE TABLE fault_injection_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_snapshot_id BIGINT NOT NULL
        REFERENCES procedure_snapshot(id) ON DELETE RESTRICT,
    scenario VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'QUEUED',
    requested_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    input_payload TEXT NOT NULL,
    result_summary TEXT,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_fault_injection_run_status
        CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED')),
    CONSTRAINT chk_fault_injection_run_completion
        CHECK (completed_at IS NULL OR started_at IS NULL OR completed_at >= started_at)
);

CREATE INDEX idx_fault_injection_run_snapshot_created
    ON fault_injection_run (procedure_snapshot_id, created_at DESC);

-- A report records the assessed outcome of one immutable injection run.  The
-- snapshot FK is intentionally retained alongside the run FK so report reads
-- can be scoped by approved procedure revision without joining mutable tables.
CREATE TABLE validation_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fault_injection_run_id BIGINT NOT NULL
        REFERENCES fault_injection_run(id) ON DELETE RESTRICT,
    procedure_snapshot_id BIGINT NOT NULL
        REFERENCES procedure_snapshot(id) ON DELETE RESTRICT,
    report_version INTEGER NOT NULL DEFAULT 1,
    status VARCHAR(32) NOT NULL DEFAULT 'GENERATED',
    report_payload TEXT NOT NULL,
    generated_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_validation_report_run_version
        UNIQUE (fault_injection_run_id, report_version),
    CONSTRAINT chk_validation_report_version CHECK (report_version > 0),
    CONSTRAINT chk_validation_report_status
        CHECK (status IN ('GENERATED', 'REVIEWED', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_validation_report_snapshot_generated
    ON validation_report (procedure_snapshot_id, generated_at DESC);
