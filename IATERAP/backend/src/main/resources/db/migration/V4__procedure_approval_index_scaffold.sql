CREATE TABLE IF NOT EXISTS test_procedure (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    lru_id BIGINT NOT NULL,
    approval_status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    current_version_number INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_test_procedure_lru
        FOREIGN KEY (lru_id) REFERENCES lru (id),
    CONSTRAINT chk_test_procedure_approval_status
        CHECK (approval_status IN ('DRAFT', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'SUPERSEDED'))
);

CREATE TABLE IF NOT EXISTS test_procedure_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_test_procedure_version_procedure
        FOREIGN KEY (procedure_id) REFERENCES test_procedure (id)
);

CREATE INDEX IF NOT EXISTS idx_test_procedure_lru_approval_status
    ON test_procedure (lru_id, approval_status);

CREATE UNIQUE INDEX IF NOT EXISTS idx_test_procedure_version_procedure_version
    ON test_procedure_version (procedure_id, version_number);
