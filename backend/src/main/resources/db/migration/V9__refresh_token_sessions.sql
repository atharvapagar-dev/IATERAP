-- AI-156: persists issued refresh tokens so they can be rotated and
-- individually or collectively revoked (on logout, and on role change),
-- instead of relying purely on stateless JWT expiry.
--
-- token_id stores the JWT "jti" claim (not the raw signed token), so
-- possession of a valid signature is still required by JwtService before
-- this table is ever consulted; this table only tracks whether a given
-- previously-issued refresh token has since been rotated or revoked.
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    revoked_at TIMESTAMP,
    replaced_by_token_id VARCHAR(64),
    CONSTRAINT fk_refresh_token_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_refresh_token_token_id
    ON refresh_tokens (token_id);

CREATE INDEX IF NOT EXISTS idx_refresh_token_user_id
    ON refresh_tokens (user_id);

CREATE INDEX IF NOT EXISTS idx_refresh_token_user_revoked
    ON refresh_tokens (user_id, revoked);
