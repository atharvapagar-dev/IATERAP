CREATE TABLE IF NOT EXISTS test_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interface_id BIGINT REFERENCES interface(id),
    connector_id BIGINT REFERENCES connector(id),
    signal_library_id BIGINT REFERENCES signal_libraries(id),
    protocol_tag_id BIGINT REFERENCES protocol_tags(id),
    fault_template_id BIGINT REFERENCES fault_templates(id),
    expected_behaviour VARCHAR(1000) NOT NULL,
    expected_range VARCHAR(255),
    calibration_requirement VARCHAR(500),
    safety_notes VARCHAR(1000),
    acceptance_criteria VARCHAR(1000) NOT NULL,
    preconditions VARCHAR(1000),
    dependencies VARCHAR(1000),
    execution_order INTEGER NOT NULL,
    post_conditions VARCHAR(1000),
    pass_fail_criteria VARCHAR(1000) NOT NULL,
    expected_observation VARCHAR(1000),
    engineer_remarks VARCHAR(1000),
    approval_status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    version_number INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_test_step_approval_status
        CHECK (approval_status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED'))
);

CREATE INDEX IF NOT EXISTS idx_test_step_interface ON test_steps (interface_id);
CREATE INDEX IF NOT EXISTS idx_test_step_execution_order ON test_steps (execution_order);