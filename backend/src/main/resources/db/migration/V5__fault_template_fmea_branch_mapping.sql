CREATE TABLE IF NOT EXISTS fault_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    fault_code VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    severity VARCHAR(50) NOT NULL DEFAULT 'NORMAL',
    lru_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_fault_template_lru
        FOREIGN KEY (lru_id) REFERENCES lru (id),
    CONSTRAINT chk_fault_template_severity
        CHECK (severity IN ('NORMAL', 'WARNING', 'CRITICAL', 'CATASTROPHIC'))
);

CREATE INDEX IF NOT EXISTS idx_fault_template_lru
    ON fault_templates (lru_id);

CREATE UNIQUE INDEX IF NOT EXISTS idx_fault_template_lru_fault_code
    ON fault_templates (lru_id, fault_code);

CREATE TABLE IF NOT EXISTS fmea_branch_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fmea_branch_code VARCHAR(100) NOT NULL,
    failure_effect VARCHAR(1000) NOT NULL,
    failure_cause VARCHAR(1000),
    detection_method VARCHAR(500),
    recommended_action VARCHAR(1000),
    risk_priority_number INTEGER,
    lru_id BIGINT NOT NULL,
    fault_template_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_fmea_branch_mapping_lru
        FOREIGN KEY (lru_id) REFERENCES lru (id),
    CONSTRAINT fk_fmea_branch_mapping_fault_template
        FOREIGN KEY (fault_template_id) REFERENCES fault_templates (id),
    CONSTRAINT chk_fmea_branch_mapping_rpn
        CHECK (risk_priority_number IS NULL OR risk_priority_number BETWEEN 1 AND 1000)
);

CREATE INDEX IF NOT EXISTS idx_fmea_branch_mapping_lru
    ON fmea_branch_mappings (lru_id);

CREATE INDEX IF NOT EXISTS idx_fmea_branch_mapping_fault_template
    ON fmea_branch_mappings (fault_template_id);

CREATE UNIQUE INDEX IF NOT EXISTS idx_fmea_branch_mapping_template_branch_code
    ON fmea_branch_mappings (fault_template_id, fmea_branch_code);
