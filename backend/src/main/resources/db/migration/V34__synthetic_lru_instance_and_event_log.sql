-- Synthetic fleet evidence for reliability analysis. These rows are explicitly
-- synthetic and must never be mistaken for live aircraft telemetry.
CREATE TABLE synthetic_lru_instance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lru_id BIGINT NOT NULL REFERENCES lru(id) ON DELETE RESTRICT,
    instance_code VARCHAR(128) NOT NULL,
    lifecycle_status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    generator_seed BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    retired_at TIMESTAMP,
    CONSTRAINT uq_synthetic_lru_instance_code UNIQUE (instance_code),
    CONSTRAINT uq_synthetic_lru_instance_lru UNIQUE (id, lru_id),
    CONSTRAINT chk_synthetic_lru_instance_status
        CHECK (lifecycle_status IN ('ACTIVE', 'RETIRED')),
    CONSTRAINT chk_synthetic_lru_instance_retirement
        CHECK (retired_at IS NULL OR retired_at >= created_at)
);

CREATE INDEX idx_synthetic_lru_instance_lru_status
    ON synthetic_lru_instance (lru_id, lifecycle_status);

-- Append-only synthetic occurrence record. The composite foreign key keeps the
-- denormalised lru_id consistent with its synthetic LRU instance, while the
-- requested composite index supports LRU/type/time trend queries directly.
CREATE TABLE event_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    synthetic_lru_instance_id BIGINT NOT NULL,
    lru_id BIGINT NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    severity VARCHAR(16) NOT NULL DEFAULT 'INFO',
    timestamp TIMESTAMP NOT NULL,
    payload TEXT,
    generated_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_event_log_synthetic_instance_lru
        FOREIGN KEY (synthetic_lru_instance_id, lru_id)
        REFERENCES synthetic_lru_instance (id, lru_id) ON DELETE RESTRICT,
    CONSTRAINT chk_event_log_severity
        CHECK (severity IN ('INFO', 'WARNING', 'ERROR', 'CRITICAL'))
);

CREATE INDEX idx_event_log_lru_type_timestamp
    ON event_log (lru_id, event_type, timestamp DESC);

CREATE INDEX idx_event_log_instance_timestamp
    ON event_log (synthetic_lru_instance_id, timestamp DESC);
