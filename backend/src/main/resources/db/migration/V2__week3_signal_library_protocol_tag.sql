CREATE TABLE IF NOT EXISTS signal_libraries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    engineering_unit VARCHAR(255),
    interface_id BIGINT NOT NULL,
    lru_id BIGINT NOT NULL,
    CONSTRAINT fk_signal_library_interface
        FOREIGN KEY (interface_id) REFERENCES "interface" (id),
    CONSTRAINT fk_signal_library_lru
        FOREIGN KEY (lru_id) REFERENCES lru (id)
);

CREATE TABLE IF NOT EXISTS signal_ranges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    minimum_value NUMERIC(38, 2) NOT NULL,
    maximum_value NUMERIC(38, 2) NOT NULL,
    severity VARCHAR(255),
    signal_library_id BIGINT NOT NULL,
    CONSTRAINT fk_signal_range_signal_library
        FOREIGN KEY (signal_library_id) REFERENCES signal_libraries (id)
);

CREATE TABLE IF NOT EXISTS protocol_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    value VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    lru_id BIGINT NOT NULL,
    CONSTRAINT fk_protocol_tag_lru
        FOREIGN KEY (lru_id) REFERENCES lru (id)
);

