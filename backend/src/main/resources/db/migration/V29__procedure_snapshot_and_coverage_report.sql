CREATE TABLE procedure_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_procedure_id BIGINT NOT NULL REFERENCES test_procedures(id),
    procedure_version_number INTEGER NOT NULL,
    approval_status VARCHAR(50) NOT NULL,
    snapshot_payload TEXT NOT NULL,
    created_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    snapshot_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_procedure_snapshot_version UNIQUE (test_procedure_id, procedure_version_number)
);
CREATE INDEX idx_procedure_snapshot_procedure ON procedure_snapshot (test_procedure_id);

CREATE TABLE coverage_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_snapshot_id BIGINT NOT NULL REFERENCES procedure_snapshot(id),
    test_procedure_id BIGINT NOT NULL REFERENCES test_procedures(id),
    procedure_version_number INTEGER NOT NULL,
    report_version INTEGER NOT NULL DEFAULT 1,
    report_payload TEXT NOT NULL,
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_coverage_report_snapshot_version UNIQUE (procedure_snapshot_id, report_version),
    CONSTRAINT uq_coverage_report_procedure_version UNIQUE (test_procedure_id, procedure_version_number, report_version)
);
CREATE INDEX idx_coverage_report_procedure ON coverage_report (test_procedure_id, procedure_version_number);
