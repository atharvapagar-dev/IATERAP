-- Row-level comparison evidence. A run may contain at most one reading per step.
CREATE TABLE IF NOT EXISTS validation_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_run_id BIGINT NOT NULL REFERENCES validation_runs(id),
    test_step_id BIGINT NOT NULL REFERENCES test_steps(id),
    source_row_number INTEGER,
    observed_value NUMERIC(30, 10),
    observed_unit VARCHAR(32),
    normalized_value NUMERIC(30, 10),
    observed_behaviour VARCHAR(1000),
    result VARCHAR(32) NOT NULL,
    deviation NUMERIC(30, 10),
    error_message VARCHAR(1000),
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_validation_reading_step UNIQUE (validation_run_id, test_step_id),
    CONSTRAINT chk_validation_reading_result
        CHECK (result IN ('MATCH', 'MISMATCH', 'OUTLIER', 'MISSING')),
    CONSTRAINT chk_validation_reading_payload CHECK (
        result = 'MISSING'
        OR observed_value IS NOT NULL
        OR observed_behaviour IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS idx_validation_reading_run ON validation_readings (validation_run_id);
CREATE INDEX IF NOT EXISTS idx_validation_reading_step ON validation_readings (test_step_id);
