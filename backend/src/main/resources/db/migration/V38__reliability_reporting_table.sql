CREATE TABLE reliability_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lru_id BIGINT NOT NULL REFERENCES lru(id) ON DELETE RESTRICT,
    lru_name VARCHAR(255) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    operating_hours DOUBLE PRECISION NOT NULL,
    failures BIGINT NOT NULL,
    repairs BIGINT NOT NULL,
    mtbf_hours DOUBLE PRECISION,
    mttr_hours DOUBLE PRECISION,
    failure_rate_per_hour DOUBLE PRECISION,
    calculated_at TIMESTAMP NOT NULL,
    source VARCHAR(32) NOT NULL DEFAULT 'SYNTHETIC',
    CONSTRAINT chk_reliability_report_period CHECK (period_end >= period_start),
    CONSTRAINT uq_reliability_report_lru_period UNIQUE (lru_id, period_start)
);

CREATE INDEX idx_reliability_report_period_lru ON reliability_report (period_start DESC, lru_id);
