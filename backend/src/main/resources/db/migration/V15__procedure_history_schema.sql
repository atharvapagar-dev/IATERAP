-- V15: Version Management -- immutable Procedure revisions (AI-173 / T6-B1).
--
-- Every content-changing save of a TestProcedure writes one new,
-- never-updated row here. The full ordered set of TestSteps at save time
-- is captured as a JSON snapshot in steps_snapshot (TEXT), following the
-- same "serialized snapshot in a TEXT column" convention already
-- established by audit_log.before_state / after_state (V6), rather than
-- introducing a parallel mutable-row-per-step history scheme that could
-- be edited later.
--
-- created_by is stored as a plain username string (SYSTEM if
-- unauthenticated), mirroring audit_log.actor's existing convention,
-- rather than a new User FK.

CREATE TABLE IF NOT EXISTS procedure_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_procedure_id BIGINT NOT NULL REFERENCES test_procedures(id),
    version_number INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    lru_id BIGINT NOT NULL,
    approval_status VARCHAR(50) NOT NULL,
    steps_snapshot TEXT NOT NULL,
    created_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_procedure_history_version UNIQUE (test_procedure_id, version_number)
);

CREATE INDEX IF NOT EXISTS idx_procedure_history_procedure ON procedure_history (test_procedure_id);
